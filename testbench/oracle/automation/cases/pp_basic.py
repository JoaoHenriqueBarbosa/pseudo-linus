"""pyppeteer 2.0.0 (Puppeteer em Python): lançar, navegar, avaliar, preencher, clicar, esperar, capturar, eventos."""
import asyncio, struct
from pyppeteer import launch
from common import BASE, record_pyppeteer, serve, step


async def main():
    record_pyppeteer()
    serve()
    browser = await launch(executablePath="/usr/bin/chromium", headless=True, args=["--no-sandbox", "--disable-gpu"],
                           handleSIGINT=False, handleSIGTERM=False, handleSIGHUP=False)
    await step("version", asyncio.sleep(0, (await browser.version()).split("/")[0]))
    await step("ws-endpoint", asyncio.sleep(0, browser.wsEndpoint.split("/devtools/")[1].split("/")[0]))
    page = await browser.newPage()
    consoles, errors, requests = [], [], []
    page.on("console", lambda m: consoles.append([m.type, m.text]))
    page.on("pageerror", lambda e: errors.append(str(e).splitlines()[0]))
    page.on("request", lambda r: requests.append([r.method, r.url[-12:], r.resourceType]))
    await step("goto", asyncio.sleep(0, (lambda r: [r.status, r.url[-12:], r.ok])(await page.goto(BASE + "/"))))
    await step("title", page.title())
    await step("url", asyncio.sleep(0, page.url))
    await step("content-head", asyncio.sleep(0, (await page.content())[:40]))
    await step("evaluate", page.evaluate("() => [1, 'a', {x: 1}]"))
    await step("evaluate-arg", page.evaluate("x => x * 2", 21))
    await step("evaluate-promise", page.evaluate("() => later()"))
    await step("evaluate-throw", page.evaluate("() => fail()"))
    await step("$eval", page.Jeval("#title", "e => e.textContent"))
    await step("$$eval", page.JJeval("li", "es => es.map(e => e.textContent)"))
    await step("$", asyncio.sleep(0, (await page.J("#title")) is not None))
    await step("$-missing", asyncio.sleep(0, await page.J("#nao")))
    await step("$$", asyncio.sleep(0, len(await page.JJ("li"))))
    await step("type", page.type("#name", "Hal"))
    await step("click", page.click("#go"))
    await step("out", page.Jeval("#out", "e => e.textContent"))
    await step("waitForSelector", asyncio.sleep(0, (await page.waitForSelector("#title[data-ready='1']", timeout=3000)) is not None))
    await step("waitForFunction", asyncio.sleep(0, (await page.waitForFunction("document.getElementById('out').textContent.length > 0")) is not None))
    await step("waitForSelector-timeout", page.waitForSelector("#nao", timeout=300))
    await step("select", page.select("#color", "g"))
    await step("focus", page.focus("#name"))
    await step("keyboard", page.keyboard.press("Enter"))
    await step("hover", page.hover("#box"))
    await step("setViewport", page.setViewport({"width": 500, "height": 300}))
    await step("viewport", asyncio.sleep(0, page.viewport))
    await step("inner", page.evaluate("() => [innerWidth, innerHeight]"))
    await step("cookies-set", page.setCookie({"name": "k", "value": "v", "url": BASE}))
    await step("cookies", asyncio.sleep(0, [[c["name"], c["value"]] for c in await page.cookies()]))
    await step("setUserAgent", page.setUserAgent("PP-Teste/1.0"))
    await step("ua", page.evaluate("() => navigator.userAgent"))
    await step("emulateMedia", page.emulateMedia("print"))
    await step("print", page.evaluate("() => matchMedia('print').matches"))
    await step("screenshot", asyncio.sleep(0, (lambda d: struct.unpack(">II", d[16:24]))(await page.screenshot())))
    await step("pdf", asyncio.sleep(0, (await page.pdf())[:5]))
    await step("setContent", page.setContent("<p id=x>novo</p>"))
    await step("setContent-text", page.Jeval("#x", "e => e.textContent"))
    await step("addScriptTag", asyncio.sleep(0, (await page.addScriptTag({"content": "window.__x = 5"})) is not None))
    await step("added", page.evaluate("() => window.__x"))
    await step("reload", asyncio.sleep(0, (await page.reload()).status))
    await step("goBack", page.goBack())
    await step("target", asyncio.sleep(0, [page.target.type, len(browser.targets())]))
    await step("pages", asyncio.sleep(0, len(await browser.pages())))
    await step("consoles", asyncio.sleep(0, consoles))
    await step("errors", asyncio.sleep(0, errors))
    await step("requests", asyncio.sleep(0, requests))
    await page.close()
    await browser.close()


asyncio.run(main())
