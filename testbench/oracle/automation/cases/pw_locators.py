"""Playwright (async): localizadores, `expect`, esperas por seletor, função e estado."""
import asyncio
from playwright.async_api import async_playwright, expect
from common import BASE, EXE, serve, step


async def main():
    serve()
    async with async_playwright() as p:
        browser = await p.chromium.launch(executable_path=EXE)
        page = await browser.new_page()
        await page.goto(BASE + "/")
        await step("by_role-button", page.get_by_role("button", name="Enviar").text_content())
        await step("by_role-heading", page.get_by_role("heading").text_content())
        await step("by_role-checkbox", page.get_by_role("checkbox", name="Concordo").is_checked())
        await step("by_role-link", page.get_by_role("link").get_attribute("href"))
        await step("by_label", page.get_by_label("Nome").get_attribute("id"))
        await step("by_placeholder", page.get_by_placeholder("seu nome").get_attribute("id"))
        await step("by_text", page.get_by_text("dois").text_content())
        await step("by_text-exact", page.get_by_text("um", exact=True).text_content())
        await step("by_test_id", page.get_by_test_id("nada").count())
        await step("css-count", page.locator("li").count())
        await step("nth", page.locator("li").nth(2).text_content())
        await step("first-last", asyncio.sleep(0, [await page.locator("li").first.text_content(), await page.locator("li").last.text_content()]))
        await step("all_text_contents", page.locator("li").all_text_contents())
        await step("all_inner_texts", page.locator("li").all_inner_texts())
        await step("filter", page.locator("li").filter(has_text="dois").count())
        await step("filter-not", page.locator("li").filter(has_not_text="dois").count())
        await step("chain", page.locator("ul").locator("li").nth(1).text_content())
        await step("xpath", page.locator("xpath=//li[2]").text_content())
        await step("text-selector", page.locator("text=três").count())
        await step("locator-fill", page.locator("#name").fill("Cris"))
        await step("locator-value", page.locator("#name").input_value())
        await step("locator-click", page.locator("#go").click())
        await step("locator-out", page.locator("#out").inner_text())
        await step("locator-evaluate", page.locator("#title").evaluate("e => e.id"))
        await step("locator-evaluate_all", page.locator("li").evaluate_all("es => es.length"))
        await step("locator-bbox", asyncio.sleep(0, bool(await page.locator("#box").bounding_box())))
        await step("locator-is_visible", page.locator("#box").is_visible())
        await step("locator-wait_for", page.locator("#box").wait_for(state="visible"))
        await step("locator-wait_for-attached-missing", page.locator("#nao").wait_for(state="attached", timeout=300))
        await step("expect-text", expect(page.locator("#title")).to_have_text("Olá, automação"))
        await step("expect-visible", expect(page.locator("#box")).to_be_visible())
        await step("expect-hidden-fail", expect(page.locator("#box")).to_be_hidden(timeout=300))
        await step("expect-value", expect(page.locator("#name")).to_have_value("Cris"))
        await step("expect-count", expect(page.locator("li")).to_have_count(3))
        await step("expect-attr", expect(page.locator("#link")).to_have_attribute("href", "/second.html"))
        await step("expect-title", expect(page).to_have_title("Fixture da automação"))
        await step("expect-url", expect(page).to_have_url(BASE + "/"))
        await step("expect-not", expect(page.locator("#nao")).not_to_be_visible())
        await step("expect-css", expect(page.locator("#box")).to_have_css("width", "120px"))
        await step("wait_for_selector", page.wait_for_selector("#title[data-ready='1']", timeout=3000))
        await step("wait_for_selector-detached", page.wait_for_selector("#nao", state="detached", timeout=300))
        await step("wait_for_timeout", page.wait_for_timeout(10))
        await step("strict-violation", page.locator("li").text_content(timeout=300))
        await step("aria-snapshot", asyncio.sleep(0, (await page.locator("body").aria_snapshot())[:80]))
        await browser.close()


asyncio.run(main())
