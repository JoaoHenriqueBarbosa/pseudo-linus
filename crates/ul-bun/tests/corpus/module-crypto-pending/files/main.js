
const crypto = require("node:crypto");
const out = [];
const log = (...a) => out.push(a.map(x => typeof x === "string" ? x : Bun.inspect(x)).join(" "));
const t = (label, fn) => { try { log(label, fn()); } catch (e) { log(label, "throws", e.name, e.code, e.message); } };
const hex = b => Buffer.from(b).toString("hex");
t("pbkdf2Sync sha1", () => hex(crypto.pbkdf2Sync("pw", "salt", 1, 20, "sha1")));
t("pbkdf2Sync sha256", () => hex(crypto.pbkdf2Sync("pw", "salt", 1000, 32, "sha256")));
t("pbkdf2Sync bufs", () => hex(crypto.pbkdf2Sync(Buffer.from("pw"), new Uint8Array(4), 2, 8, "sha512")));
t("pbkdf2Sync bad digest", () => crypto.pbkdf2Sync("pw", "salt", 1, 20, "nope"));
t("pbkdf2Sync noargs", () => crypto.pbkdf2Sync());
t("pbkdf2Sync iterations", () => crypto.pbkdf2Sync("pw", "salt", 0, 20, "sha1"));
t("pbkdf2Sync keylen", () => crypto.pbkdf2Sync("pw", "salt", 1, -1, "sha1"));
t("pbkdf2Sync keylen 0", () => crypto.pbkdf2Sync("pw", "salt", 1, 0, "sha1"));
t("pbkdf2Sync nodigest", () => crypto.pbkdf2Sync("pw", "salt", 1, 4));
t("pbkdf2 nocb", () => crypto.pbkdf2("pw", "salt", 1, 8, "sha1"));
t("pbkdf2 shapes", () => [crypto.pbkdf2.length, crypto.pbkdf2Sync.length, crypto.pbkdf2.name, crypto.pbkdf2Sync.name]);
t("scryptSync", () => hex(crypto.scryptSync("pw", "salt", 16)));
t("scryptSync opts", () => hex(crypto.scryptSync("pw", "salt", 16, { N: 1024, r: 8, p: 1 })));
t("scryptSync bad N", () => crypto.scryptSync("pw", "salt", 16, { N: 3 }));
t("scryptSync noargs", () => crypto.scryptSync());
t("scrypt shapes", () => [crypto.scrypt.length, crypto.scryptSync.length]);
t("hkdfSync", () => hex(crypto.hkdfSync("sha256", "key", "salt", "info", 16)));
t("hkdfSync bad digest", () => crypto.hkdfSync("nope", "key", "salt", "info", 16));
t("hkdfSync noargs", () => crypto.hkdfSync());
t("hkdfSync too long", () => crypto.hkdfSync("sha256", "key", "salt", "info", 255 * 32 + 1));
t("hkdfSync type", () => Object.prototype.toString.call(crypto.hkdfSync("sha256", "key", "salt", "info", 16)));
t("hkdf shapes", () => [crypto.hkdf.length, crypto.hkdfSync.length]);
t("cipher roundtrip", () => {
  const key = Buffer.alloc(16, 1), iv = Buffer.alloc(16, 2);
  const c = crypto.createCipheriv("aes-128-cbc", key, iv);
  const enc = Buffer.concat([c.update("hello world"), c.final()]);
  const d = crypto.createDecipheriv("aes-128-cbc", key, iv);
  return [hex(enc), Buffer.concat([d.update(enc), d.final()]).toString()];
});
t("cipher gcm", () => {
  const key = Buffer.alloc(32, 3), iv = Buffer.alloc(12, 4);
  const c = crypto.createCipheriv("aes-256-gcm", key, iv);
  const enc = Buffer.concat([c.update("secret"), c.final()]);
  return [hex(enc), hex(c.getAuthTag())];
});
t("cipher bad name", () => crypto.createCipheriv("nope", Buffer.alloc(16), Buffer.alloc(16)));
t("cipher bad key", () => crypto.createCipheriv("aes-128-cbc", Buffer.alloc(3), Buffer.alloc(16)));
t("cipher bad iv", () => crypto.createCipheriv("aes-128-cbc", Buffer.alloc(16), Buffer.alloc(3)));
t("cipher shapes", () => [crypto.Cipheriv.name, crypto.Cipheriv.length, crypto.Decipheriv.name, crypto.createCipheriv.length]);
t("getCipherInfo", () => [crypto.getCipherInfo("aes-256-gcm"), crypto.getCipherInfo("nope"), crypto.getCipherInfo(419), crypto.getCipherInfo("aes-128-cbc", { keyLength: 16 })]);
t("createSecretKey", () => { const k = crypto.createSecretKey(Buffer.from("abc")); return [k.type, k.symmetricKeySize, hex(k.export())]; });
t("hmac secret key", () => crypto.createHmac("sha1", crypto.createSecretKey(Buffer.from("k"))).update("abc").digest("hex"));
t("generateKeyPairSync ed25519", () => { const { publicKey, privateKey } = crypto.generateKeyPairSync("ed25519"); const s = crypto.sign(null, Buffer.from("m"), privateKey); return [publicKey.type, privateKey.type, s.length, crypto.verify(null, Buffer.from("m"), publicKey, s)]; });
t("createSign", () => { const { publicKey, privateKey } = crypto.generateKeyPairSync("rsa", { modulusLength: 1024 }); const s = crypto.createSign("sha256").update("m").sign(privateKey); return [s.length, crypto.createVerify("sha256").update("m").verify(publicKey, s)]; });
t("diffieHellman", () => { const a = crypto.createECDH("prime256v1"); const b = crypto.createECDH("prime256v1"); a.generateKeys(); b.generateKeys(); return a.computeSecret(b.getPublicKey()).equals(b.computeSecret(a.getPublicKey())); });
t("checkPrimeSync", () => [crypto.checkPrimeSync(7n), crypto.checkPrimeSync(8n)]);
t("generatePrimeSync", () => crypto.generatePrimeSync(16, { bigint: true }) > 0n);
t("publicEncrypt", () => { const { publicKey, privateKey } = crypto.generateKeyPairSync("rsa", { modulusLength: 1024 }); return crypto.privateDecrypt(privateKey, crypto.publicEncrypt(publicKey, Buffer.from("x"))).toString(); });
t("X509Certificate", () => typeof crypto.X509Certificate);
t("KeyObject", () => [typeof crypto.KeyObject, crypto.KeyObject.name, crypto.KeyObject.length, typeof crypto.KeyObject.from]);
t("argon2Sync", () => hex(crypto.argon2Sync("argon2id", { message: "pw", nonce: Buffer.alloc(16, 1), parallelism: 1, tagLength: 16, memory: 8, passes: 1 })));
t("Certificate", () => [typeof crypto.Certificate, Object.keys(crypto.Certificate)]);
console.log(out.join("\n"));
process.exit(0);
