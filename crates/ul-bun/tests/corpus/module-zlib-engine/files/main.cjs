const z = require("node:zlib");
const t = (l, f) => { try { console.log(l, f()); } catch (e) { console.log(l, "throws", e.name, e.code, e.errno, e.message); } };
const text = Buffer.from("hello hello hello hello zlib zlib zlib\n".repeat(20));
t("deflate", () => z.deflateSync(text).toString("hex"));
t("gzip", () => z.gzipSync(text).toString("hex"));
t("raw", () => z.deflateRawSync(text).toString("hex"));
t("level0", () => z.deflateSync(text, { level: 0 }).length);
t("level9", () => z.deflateSync(text, { level: 9 }).toString("hex"));
t("brotli", () => z.brotliCompressSync(text).toString("hex"));
t("zstd", () => z.zstdCompressSync(text).toString("hex"));
t("roundtrip", () => z.inflateSync(z.deflateSync(text)).equals(text));
t("gunzip", () => z.gunzipSync(z.gzipSync(text)).equals(text));
t("unzip", () => z.unzipSync(z.gzipSync(text)).equals(text));
t("raw rt", () => z.inflateRawSync(z.deflateRawSync(text)).equals(text));
t("brotli rt", () => z.brotliDecompressSync(z.brotliCompressSync(text)).equals(text));
t("zstd rt", () => z.zstdDecompressSync(z.zstdCompressSync(text)).equals(text));
t("bad inflate", () => z.inflateSync(Buffer.from("garbage")));
t("bad gunzip", () => z.gunzipSync(Buffer.from("garbage")));
t("truncated", () => z.inflateSync(z.deflateSync(text).subarray(0, 10)));
t("bad arg", () => z.deflateSync(5));
t("bad level", () => z.deflateSync("a", { level: 99 }));
z.gzip(text, (e, r) => console.log("gzip cb", e, r.length));
const gz = z.createGzip();
const chunks = [];
gz.on("data", c => chunks.push(c));
gz.on("end", () => console.log("stream", Buffer.concat(chunks).toString("hex")));
gz.end(text);
