const tls = require("node:tls");
const out = [];
const log = (...a) => out.push(a.join(" "));
log("keys", Object.keys(tls).join(","));
log("DEFAULT_CIPHERS", tls.DEFAULT_CIPHERS);
log("versions", tls.DEFAULT_MIN_VERSION, tls.DEFAULT_MAX_VERSION, tls.DEFAULT_ECDH_CURVE);
log("ciphers", tls.getCiphers().length, tls.getCiphers().slice(0, 5).join(","));
log("roots", tls.rootCertificates.length, tls.rootCertificates[0].slice(0, 40).replace(/\n/g, "|"), tls.rootCertificates === tls.rootCertificates);
log("canon", tls.checkServerIdentity("::1", { subjectaltname: "IP Address:0:0:0:0:0:0:0:1", subject: {} }), tls.checkServerIdentity("example.com", { subject: { CN: "example.com" } }));
log("canon mapped", tls.checkServerIdentity("::ffff:1.2.3.4", { subjectaltname: "IP Address:0:0:0:0:0:FFFF:102:304", subject: {} }));
log("canon v6", tls.checkServerIdentity("2001:db8::1", { subjectaltname: "IP Address:2001:DB8:0:0:0:0:0:1", subject: {} }));
log("canon v4", tls.checkServerIdentity("1.2.3.4", { subjectaltname: "IP Address:1.2.3.4", subject: {} }));
const e = tls.checkServerIdentity("example.com", { subject: { CN: "other.com" } });
log("err", e.code, e.message, e.host, e.reason);
const ip = tls.checkServerIdentity("1.2.3.5", { subjectaltname: "IP Address:1.2.3.4", subject: {} });
log("ip err", ip.code, ip.message);
const dns = tls.checkServerIdentity("a.example.com", { subjectaltname: "DNS:*.example.com", subject: {} });
log("wildcard", dns);
log("proto", Object.getOwnPropertyNames(tls.TLSSocket.prototype).length, Object.getOwnPropertyNames(tls.Server.prototype).length);
console.log(out.join("\n"));
