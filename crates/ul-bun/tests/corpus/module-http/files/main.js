const http = require("node:http");
const https = require("node:https");
const dc = require("node:diagnostics_channel");
const out = [];
const log = (...a) => out.push(a.map(x => typeof x === "string" ? x : require("node:util").inspect(x)).join(" "));
const t = (label, fn) => { try { log(label, fn()); } catch (e) { log(label, "throws", e.name, e.code, e.message); } };
log("http keys", Object.keys(http).join(","));
log("https keys", Object.keys(https).join(","));
log("methods", http.METHODS.length, http.METHODS.slice(0, 6).join(","), http.METHODS[34]);
log("status", Object.keys(http.STATUS_CODES).length, http.STATUS_CODES[404], http.STATUS_CODES[418]);
log("maxHeaderSize", http.maxHeaderSize);
t("set maxHeaderSize -1", () => { http.maxHeaderSize = -1; return http.maxHeaderSize; });
t("set maxHeaderSize x", () => { http.maxHeaderSize = "x"; return http.maxHeaderSize; });
t("set maxHeaderSize 8192", () => { http.maxHeaderSize = 8192; return http.maxHeaderSize; });
t("validateHeaderName ok", () => http.validateHeaderName("x-a"));
t("validateHeaderName bad", () => http.validateHeaderName("x a"));
t("validateHeaderName empty", () => http.validateHeaderName(""));
t("validateHeaderValue undefined", () => http.validateHeaderValue("x", undefined));
t("validateHeaderValue bad", () => http.validateHeaderValue("x", "a\nb"));
const agent = new http.Agent({ keepAlive: true, maxSockets: 3 });
log("agent", agent.keepAlive, agent.maxSockets, agent.maxFreeSockets, agent.defaultPort, agent.protocol, Object.keys(agent.sockets), agent.options.keepAlive);
log("global agent", http.globalAgent instanceof http.Agent, http.globalAgent.keepAlive, http.globalAgent.maxSockets, https.globalAgent.defaultPort, https.globalAgent.protocol);
const msg = new http.OutgoingMessage();
msg.setHeader("Content-Type", "text/plain");
msg.setHeader("X-A", ["1", "2"]);
log("headers", msg.getHeaderNames().join(","), msg.getHeader("content-type"), msg.hasHeader("x-a"), msg.getHeaders());
msg.removeHeader("x-a");
log("after remove", msg.getHeaderNames().join(","), msg.headersSent, msg.writable, msg.finished);
t("setHeader bad", () => msg.setHeader("bad name", "x"));
t("setHeader undefined", () => msg.setHeader("x", undefined));
const incoming = new http.IncomingMessage(null);
log("incoming", incoming.httpVersion, incoming.headers, incoming.complete, incoming.method, incoming.url, incoming.statusCode);
t("request bad protocol", () => http.request("ftp://example.com/"));
t("request bad method", () => http.request({ method: "bad method" }));
t("request bad header", () => http.request({ headers: { "bad name": "x" } }));
const server = http.createServer();
log("server", server.listening, server.timeout, server.keepAliveTimeout, server.headersTimeout, server.requestTimeout, server.maxHeadersCount, server.maxRequestsPerSocket);
const ch = dc.channel("zz");
log("dc", ch.name, ch.hasSubscribers, dc.hasSubscribers("zz"));
let got;
dc.subscribe("zz", (m, n) => { got = [m, n]; });
ch.publish({ a: 1 });
log("dc publish", got, dc.hasSubscribers("zz"));
console.log(out.join("\n"));
