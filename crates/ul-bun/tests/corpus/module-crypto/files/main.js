
const crypto = require("node:crypto");
const out = [];
const log = (...a) => out.push(a.map(x => typeof x === "string" ? x : Bun.inspect(x)).join(" "));
const t = (label, fn) => { try { log(label, fn()); } catch (e) { log(label, "throws", e.name, e.code, e.message); } };
log("same", require("crypto") === crypto);
log("keys", Object.keys(crypto));
log("types", Object.keys(crypto).filter(k => typeof crypto[k] === "undefined"));
log("hashes", crypto.getHashes());
for (const algo of ["md5", "sha1", "sha224", "sha256", "sha384", "sha512", "sha512-256", "ripemd160", "SHA256", "sha-256", "blake2b512", "sha3-256", "nope"]) {
  t("hash " + algo, () => crypto.createHash(algo).update("abc").digest("hex"));
}
t("encodings", () => ["hex", "base64", "base64url", "latin1", "binary", "ascii", "utf8", "ucs2", "buffer", undefined].map(e => { const h = crypto.createHash("sha256").update("abc").digest(e); return typeof h === "string" ? h : Bun.inspect(h); }));
t("chain", () => { const h = crypto.createHash("sha1"); return h.update("a") === h; });
t("update enc", () => crypto.createHash("sha1").update("6162", "hex").update(Buffer.from("63")).update(new Uint8Array([100])).update(new DataView(new ArrayBuffer(2))).digest("hex"));
t("update bad", () => crypto.createHash("sha1").update(1));
t("update null", () => crypto.createHash("sha1").update(null));
t("update obj", () => crypto.createHash("sha1").update({}));
t("digest twice", () => { const h = crypto.createHash("sha1"); h.digest(); return h.digest(); });
t("update after digest", () => { const h = crypto.createHash("sha1"); h.digest(); return h.update("x"); });
t("copy", () => { const h = crypto.createHash("sha1").update("a"); const c = h.copy(); c.update("b"); return [h.digest("hex"), c.digest("hex")]; });
t("copy after digest", () => { const h = crypto.createHash("sha1"); h.digest(); return h.copy(); });
t("no args", () => crypto.createHash());
t("bad algo type", () => crypto.createHash(1));
t("xof", () => crypto.createHash("shake128", { outputLength: 4 }).update("abc").digest("hex"));
t("stream", () => { const h = crypto.createHash("md5"); h.end("abc"); return h.read().toString("hex"); });
t("hash fn", () => crypto.hash("sha1", "abc"));
t("hash fn enc", () => crypto.hash("sha1", "abc", "base64"));
t("hmac", () => crypto.createHmac("sha256", "key").update("abc").digest("hex"));
t("hmac buf key", () => crypto.createHmac("sha1", Buffer.from("k")).update("abc").digest("base64"));
t("hmac empty key", () => crypto.createHmac("sha1", "").update("abc").digest("hex"));
t("hmac bad algo", () => crypto.createHmac("nope", "k"));
t("hmac bad key", () => crypto.createHmac("sha1", 1));
t("hmac twice", () => { const h = crypto.createHmac("sha1", "k"); h.digest(); return h.digest("hex"); });
t("hmac no key", () => crypto.createHmac("sha1"));
t("ctor shapes", () => [typeof crypto.Hash, crypto.Hash.name, crypto.Hash.length, crypto.createHash.name, crypto.createHash.length, crypto.createHmac.length, typeof crypto.Hmac]);
t("instanceof", () => { const h = crypto.createHash("sha1"); return [h instanceof crypto.Hash, h instanceof require("node:stream").Transform, Object.getOwnPropertyNames(Object.getPrototypeOf(h))]; });
t("randomBytes", () => { const b = crypto.randomBytes(8); return [b.length, Buffer.isBuffer(b), b.constructor.name]; });
t("randomBytes 0", () => crypto.randomBytes(0).length);
t("randomBytes neg", () => crypto.randomBytes(-1));
t("randomBytes str", () => crypto.randomBytes("8"));
t("randomBytes big", () => crypto.randomBytes(2 ** 31));
t("randomBytes frac", () => crypto.randomBytes(1.5).length);
t("randomBytes nan", () => crypto.randomBytes(NaN));
t("randomBytes undef", () => crypto.randomBytes());
t("randomFillSync", () => { const b = Buffer.alloc(8); const r = crypto.randomFillSync(b); return [r === b, b.some(x => x !== 0)]; });
t("randomFillSync offset", () => { const b = Buffer.alloc(8); crypto.randomFillSync(b, 4); return [b.slice(0, 4).every(x => x === 0), b.slice(4).some(x => x !== 0)]; });
t("randomFillSync bad", () => crypto.randomFillSync("x"));
t("randomFillSync range", () => crypto.randomFillSync(Buffer.alloc(4), 5));
t("randomFillSync size", () => crypto.randomFillSync(Buffer.alloc(4), 1, 9));
t("randomFillSync ab", () => crypto.randomFillSync(new ArrayBuffer(4)).byteLength);
t("randomFillSync u32", () => crypto.randomFillSync(new Uint32Array(2)).length);
t("randomUUID", () => /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/.test(crypto.randomUUID()));
t("randomUUID opts", () => crypto.randomUUID({ disableEntropyCache: true }).length);
t("randomUUID bad", () => crypto.randomUUID(1));
t("randomInt", () => { const n = crypto.randomInt(10); return n >= 0 && n < 10; });
t("randomInt range", () => { const n = crypto.randomInt(5, 7); return n >= 5 && n < 7; });
t("randomInt bad", () => crypto.randomInt(0));
t("randomInt bad2", () => crypto.randomInt(5, 5));
t("randomInt type", () => crypto.randomInt("a"));
t("timingSafeEqual", () => [crypto.timingSafeEqual(Buffer.from("a"), Buffer.from("a")), crypto.timingSafeEqual(Buffer.from("a"), Buffer.from("b"))]);
t("timingSafeEqual len", () => crypto.timingSafeEqual(Buffer.from("a"), Buffer.from("ab")));
t("timingSafeEqual type", () => crypto.timingSafeEqual("a", "a"));
t("getRandomValues", () => crypto.getRandomValues(new Uint8Array(4)).length);
t("webcrypto", () => [crypto.webcrypto === globalThis.crypto, crypto.subtle === globalThis.crypto.subtle]);
t("constants", () => Object.keys(crypto.constants).length > 0);
t("getCiphers", () => typeof crypto.getCiphers);
t("getCurves", () => crypto.getCurves().length > 0);
t("fn names", () => [crypto.randomBytes.name, crypto.randomBytes.length, crypto.randomFillSync.length, crypto.randomUUID.length, crypto.randomInt.length, crypto.timingSafeEqual.length, crypto.getHashes.length, crypto.getRandomValues.name, crypto.getRandomValues.length]);
console.log(out.join("\n"));
process.exit(0);
