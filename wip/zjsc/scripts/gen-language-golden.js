const lines = [];
const seen = new Set();
for (const source of programs) {
  if (seen.has(source)) continue;
  seen.add(source);
  if (/[\t\n\r]/.test(source)) {
    process.stderr.write("fonte com tab ou quebra de linha: " + JSON.stringify(source) + "\n");
    process.exitCode = 1;
    continue;
  }
  if (/[\u2013\u2014]/.test(source)) throw new Error("travessão na fonte: " + source);
  const run = spawnSync(process.execPath, [__filename, "--run", source], { encoding: "utf8", timeout: 10000, killSignal: "SIGKILL" });
  let result;
  if (run.error || run.status !== 0) result = "timeout\t" + (run.error ? run.error.code : "status " + run.status);
  else result = run.stdout;
  if (/\/home\/|\/Users\/|node_modules|\.bun/.test(result)) throw new Error("caminho da máquina no resultado: " + source + " => " + result);
  lines.push(source + "\t" + result.replace(/[\n\r]/g, "\\n"));
}
