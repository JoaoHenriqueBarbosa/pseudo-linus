// ---- Execução.
const dir = fs.mkdtempSync(path.join(os.tmpdir(), "sloppy-syntax-golden-"));
const file = path.join(dir, "sloppy_syntax_case.js");
const preload = path.join(dir, "preload.js");
// O bun roda arquivos como módulo (estrito); o programa precisa de semântica de script sloppy, então o preload o
// executa com vm.runInThisContext e o arquivo principal fica vazio.
fs.writeFileSync(
  preload,
  "const vm = require('vm'); const src = require('fs').readFileSync(" + JSON.stringify(file) + ", 'utf8');\n" +
    "process.on('exit', () => { process.stdout.write('\\u0001' + JSON.stringify(globalThis.R === undefined ? '<undefined>' : String(globalThis.R)) + '\\n') });\n" +
    "try { vm.runInThisContext(src, { filename: 'sloppy_syntax_case.js' }) } catch (e) { globalThis.R = undefined }\n",
);
const runner = path.join(dir, "runner.js");
fs.writeFileSync(runner, "");
const prefix = dir + "/";
const seen = new Set();
let kept = 0;
let dropped = 0;
for (const body of programs) {
  if (seen.has(body)) continue;
  seen.add(body);
  fs.writeFileSync(file, body);
  const run = spawnSync(process.execPath, ["--preload", preload, runner], { encoding: "utf8", cwd: dir, timeout: 20000 });
  const marked = (run.stdout || "").split("\n").find(line => line.startsWith("\u0001"));
  if (!marked) {
    dropped++;
    process.stderr.write("sem resultado para: " + JSON.stringify(body.slice(0, 120)) + "\n");
    continue;
  }
  const result = JSON.parse(marked.slice(1)).split("file://" + prefix).join("file:///").split(prefix).join("");
  if (result.includes(dir) || /\/home\/|\/tmp\/|\/Users\//.test(result)) {
    dropped++;
    process.stderr.write("caminho da máquina no resultado: " + JSON.stringify(body.slice(0, 120)) + "\n");
    continue;
  }
  kept++;
  emitRow(JSON.stringify(body) + "\t" + JSON.stringify(result));
}
process.stderr.write(`mantidos ${kept}, descartados ${dropped}\n`);
fs.rmSync(dir, { recursive: true, force: true });
