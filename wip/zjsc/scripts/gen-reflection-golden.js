// Registro de chamadas: o log guarda o nome da trap e os argumentos relevantes.
const LOG = "var log = []; var h = new Proxy({}, {get(t, k) { return function (...a) { log.push(k); return Reflect[k](...a); }; }}); ";

// 1. As 13 traps, ordem e argumentos.
const trapOps = {
  get: "p.x",
  set: "p.x = 1",
  has: "'x' in p",
  deleteProperty: "delete p.x",
  defineProperty: "Object.defineProperty(p, 'x', {value: 1, configurable: true})",
  getOwnPropertyDescriptor: "Object.getOwnPropertyDescriptor(p, 'x')",
  ownKeys: "Reflect.ownKeys(p)",
  getPrototypeOf: "Object.getPrototypeOf(p)",
  setPrototypeOf: "Object.setPrototypeOf(p, null)",
  isExtensible: "Object.isExtensible(p)",
  preventExtensions: "Object.preventExtensions(p)",
  apply: "p()",
  construct: "new p()",
};
for (const [trap, op] of Object.entries(trapOps)) {
  const target = trap === "apply" || trap === "construct" ? "function () { return {a: 1}; }" : "{x: 0}";
  add(
    `${LOG}var p = new Proxy(${target}, h); ${op}; log.join()`,
    `var seen; var p = new Proxy(${target}, {${trap}(...a) { seen = a.length + typeof a[0] + typeof a[1]; return Reflect.${trap === "apply" ? "apply" : trap}(...a); }}); try { ${op}; } catch (e) {} seen`,
    `var p = new Proxy(${target}, {${trap}: 1}); ${op}`,
    `var p = new Proxy(${target}, {${trap}: null}); ${op}; 'ok'`,
    `var p = new Proxy(${target}, {${trap}: undefined}); ${op}; 'ok'`,
    `var p = new Proxy(${target}, {get ${trap}() { throw new RangeError('g'); }}); ${op}`,
    `var p = new Proxy(${target}, {${trap}() { throw new SyntaxError('boom'); }}); ${op}`,
    `var self; var p = new Proxy(${target}, {${trap}() { self = this; return Reflect.${trap}(...arguments); }}); try { ${op}; } catch (e) {} typeof self`
  );
}

