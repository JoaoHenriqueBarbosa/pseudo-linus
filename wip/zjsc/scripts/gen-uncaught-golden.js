// Gera tests/golden/uncaught_bun.tsv no bun 1.4.2: o que o processo escreve no stderr (bytes, em hexadecimal) e o código
// de saída quando o script termina com exceção não capturada. Cada caso roda num processo bun próprio, a partir de um
// arquivo `main.js` copiado para um diretório temporário; o caminho do diretório é trocado por `/app` no stderr.
// Formato: `JSON(fonte)<TAB>hex(stderr normalizado)<TAB>código de saída`. Uso: bun scripts/gen-uncaught-golden.js
