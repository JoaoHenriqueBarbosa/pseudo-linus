//! Golden da resolução de especificador nu por `node_modules` contra o bun 1.4.2: `tests/golden/node_modules_resolve_bun.tsv`
//! e a árvore em `tests/golden/node_modules_resolve_tree.json` saem de `scripts/gen-node-modules-resolve-golden.js`.
//! Cada linha do TSV é `importador<TAB>JSON(especificador)<TAB>require.resolve<TAB>import.meta.resolve`, com caminhos
//! relativos à raiz da árvore e erros como `ERR <mensagem>` (quebra de linha escrita `\n`). O `withexp` só passa
//! depois da fatia de `exports`: fica comparado, não excluído.
mod common;

use common::{json_string, json_string_array};
use zjsc::api::module_probe::{import_not_found_message, require_not_found_message, resolve_node_modules, MemoryFs};

const GOLDEN: &str = include_str!("golden/node_modules_resolve_bun.tsv");
const TREE: &str = include_str!("golden/node_modules_resolve_tree.json");

/// Pares `[a,b]` de uma das listas do JSON da árvore (uma entrada por linha, a partir da linha `"<nome>": [`).
fn pairs(section: &str) -> Vec<(String, String)> {
    let start = TREE.find(&format!("\"{section}\": [")).expect("seção da árvore");
    TREE[start..]
        .lines()
        .skip(1)
        .take_while(|line| line.trim_start().starts_with('['))
        .map(|line| {
            let cells = json_string_array(line.trim().trim_end_matches(',')).expect("par JSON");
            assert_eq!(cells.len(), 2);
            let text = |units: &Vec<u16>| String::from_utf16(units).expect("UTF-8 válido");
            (text(&cells[0]), text(&cells[1]))
        })
        .collect()
}

fn tree() -> MemoryFs {
    let files = pairs("files");
    let borrowed: Vec<(String, &str)> = files.iter().map(|(path, text)| (format!("/{path}"), text.as_str())).collect();
    let refs: Vec<(&str, &str)> = borrowed.iter().map(|(path, text)| (path.as_str(), *text)).collect();
    pairs("links").iter().fold(MemoryFs::new(&refs), |fs, (link, target)| fs.with_link(&format!("/{link}"), target))
}

#[test]
fn node_modules_resolve_matches_bun() {
    let fs = tree();
    let mut failures = Vec::new();
    let mut total = 0;
    for line in GOLDEN.lines().filter(|line| !line.is_empty()) {
        let mut columns = line.splitn(4, '\t');
        let importer = format!("/{}", columns.next().expect("importador"));
        let specifier = json_string(columns.next().expect("especificador"));
        let expected_require = columns.next().expect("require.resolve");
        let expected_import = columns.next().expect("import.meta.resolve");
        let dir = &importer[..importer.rfind('/').expect("diretório do importador")];
        let (actual_require, actual_import) = match resolve_node_modules(&fs, dir, &specifier) {
            Some(path) => (path.clone(), format!("file://{path}")),
            None => (
                format!("ERR {}", require_not_found_message(&specifier, &importer)),
                format!("ERR {}", import_not_found_message(&specifier, &importer)),
            ),
        };
        let (actual_require, actual_import) = (actual_require.replace('\n', "\\n"), actual_import.replace('\n', "\\n"));
        total += 1;
        if actual_require != expected_require || actual_import != expected_import {
            failures.push(format!(
                "{importer} {specifier:?}\n    esperado {expected_require:?} | {expected_import:?}\n    veio     {actual_require:?} | {actual_import:?}"
            ));
        }
    }
    assert_eq!(total, 59, "o golden mudou de tamanho");
    assert!(failures.is_empty(), "{} de {} divergem do bun:\n{}", failures.len(), total, failures.join("\n"));
}
