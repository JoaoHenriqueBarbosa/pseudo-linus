/// `struct TrigEvent`: o evento de um TRIGGER. `a` é TK_UPDATE, TK_INSERT, TK_DELETE ou
/// TK_INSTEAD; em `UPDATE OF (a,b,c)`, `b` guarda a lista `a,b,c`.
#[derive(Default)]
pub struct TrigEvent {
    /// Tipo do evento.
    pub a: i32,
    /// Lista de colunas do `UPDATE OF`.
    pub b: Option<Box<IdList>>,
}

/// `struct FrameBound`: um limite de frame de janela.
#[derive(Default)]
pub struct FrameBound {
    /// TK_UNBOUNDED, TK_CURRENT, TK_PRECEDING ou TK_FOLLOWING.
    pub e_type: i32,
    /// Expressão do limite (`expr PRECEDING|FOLLOWING`).
    pub p_expr: Option<Box<Expr>>,
}

/// `struct {int value; int mask;}`: o par valor/máscara de `onconf`-like (`yy383`).
#[derive(Default, Clone, Copy)]
pub struct ValueMask {
    /// O valor.
    pub value: i32,
    /// A máscara dos bits que o valor define.
    pub mask: i32,
}

/// `YYMINORTYPE`: o valor semântico de um símbolo da pilha. Cada variante é um campo `yyNNN` da
/// união do C, com o mesmo número no nome. `Init` é o `yyinit` (entrada sem valor).
///
/// `Yy168` é o `const char*` do C, um ponteiro para dentro do texto SQL: aqui é o deslocamento
/// em bytes em `zSql` (o `i_ofst` do `Token`; o fim de um token é `i_ofst + z.len()`).
#[derive(Default)]
pub enum YyMinor {
    /// `yyinit`: sem valor (estado vazio, ou valor já movido para fora).
    #[default]
    Init,
    /// `yy0`: o token terminal.
    Yy0(Token),
    /// `yy14`: lista de expressões.
    Yy14(Option<Box<ExprList>>),
    /// `yy59`: cláusula WITH.
    Yy59(Option<Box<With>>),
    /// `yy67`: uma CTE.
    Yy67(Option<Box<Cte>>),
    /// `yy122`: upsert.
    Yy122(Option<Box<Upsert>>),
    /// `yy132`: lista de identificadores.
    Yy132(Option<Box<IdList>>),
    /// `yy144`: inteiro.
    Yy144(i32),
    /// `yy168`: deslocamento no texto SQL (ver acima).
    Yy168(i32),
    /// `yy203`: lista de tabelas fonte.
    Yy203(Option<Box<SrcList>>),
    /// `yy211`: janela (ou lista de janelas).
    Yy211(Option<Box<Window>>),
    /// `yy269`: ON ou USING.
    Yy269(OnOrUsing),
    /// `yy286`: evento de trigger.
    Yy286(TrigEvent),
    /// `yy383`: valor e máscara.
    Yy383(ValueMask),
    /// `yy391`: inteiro sem sinal de 32 bits (flags de tabela).
    Yy391(u32),
    /// `yy427`: passo de trigger.
    Yy427(Option<Box<TriggerStep>>),
    /// `yy454`: expressão.
    Yy454(Option<Box<Expr>>),
    /// `yy462`: byte.
    Yy462(u8),
    /// `yy509`: limite de frame.
    Yy509(FrameBound),
    /// `yy555`: SELECT.
    Yy555(Option<Box<Select>>),
}

/// `yyStackEntry`: um elemento da pilha. Depois da metade "shift" de um SHIFTREDUCE, `stateno`
/// guarda a ação reduce da segunda metade.
#[derive(Default)]
pub struct YyStackEntry {
    /// O número do estado, ou a ação reduce pendente de um SHIFTREDUCE.
    pub stateno: u16,
    /// O código do símbolo (o "major").
    pub major: u16,
    /// O valor semântico (o "minor").
    pub minor: YyMinor,
}

/// `yyParser`: o estado do autômato. `stack.len()` é `yystackEnd + 1` do C; `tos` é o índice de
/// `yytos`. O contexto (`pParse`) e a conexão não ficam aqui: vão por parâmetro.
pub struct YyParser {
    /// A pilha (a entrada 0 é a sentinela de estado 0).
    pub stack: Vec<YyStackEntry>,
    /// Índice do topo.
    pub tos: usize,
}

impl YyParser {
    /// `yymsp[k]`: a entrada `k` posições a partir do topo (`k` zero ou negativo; `k = 1` é a
    /// primeira posição livre, que as regras vazias escrevem antes do empilhamento).
    pub fn msp(&mut self, k: isize) -> &mut YyStackEntry {
        let i = (self.tos as isize + k) as usize;
        &mut self.stack[i]
    }

    /// `yyGrowStack`: `newSize = oldSize*2 + 100`. O `YYREALLOC` do C pode falhar (e então
    /// `yyStackOverflow` chama `sqlite3OomFault`); a alocação do `Vec` não falha observavelmente,
    /// então não há retorno de erro.
    fn grow_stack(&mut self) {
        let new_size = self.stack.len() * 2 + 100;
        self.stack.resize_with(new_size, YyStackEntry::default);
    }
}

