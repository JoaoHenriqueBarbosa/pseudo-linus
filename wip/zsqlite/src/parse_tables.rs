/// `sqlite3ParserInit`: um parser novo, pilha com a sentinela de estado 0 e `YYSTACKDEPTH`
/// entradas (o C inicializa só a entrada 0; o resto da `yystk0` é lixo, aqui `Init`).
pub fn parser_init() -> YyParser {
    let mut stack = Vec::with_capacity(YYSTACKDEPTH);
    stack.resize_with(YYSTACKDEPTH, YyStackEntry::default);
    YyParser { stack, tos: 0 }
}

/// `yy_pop_parser_stack`: desempilha uma vez; soltar o valor é o `yy_destructor`.
pub fn yy_pop_parser_stack(p: &mut YyParser) {
    debug_assert!(p.tos > 0);
    let e = &mut p.stack[p.tos];
    p.tos -= 1;
    drop(std::mem::take(&mut e.minor));
}

/// `sqlite3ParserFinalize`: solta tudo o que sobrou na pilha e a devolve ao tamanho inicial
/// (o C libera a pilha de heap se `yystack != yystk0`).
pub fn parser_finalize(p: &mut YyParser) {
    while p.tos > 0 {
        yy_pop_parser_stack(p);
    }
    p.stack.truncate(YYSTACKDEPTH);
    p.stack.shrink_to_fit();
    for e in p.stack.iter_mut() {
        e.minor = YyMinor::Init;
    }
}

/// `yy_find_shift_action`: a ação do parser para o terminal `look` no estado `stateno`.
pub fn yy_find_shift_action(mut look: u16, stateno: u16) -> u16 {
    if stateno > YY_MAX_SHIFT {
        return stateno;
    }
    debug_assert!(stateno as usize <= YY_SHIFT_COUNT);
    loop {
        let i = YY_SHIFT_OFST[stateno as usize] as usize + look as usize;
        debug_assert!(look != YYNOCODE && (look as usize) < YYNTOKEN);
        if YY_LOOKAHEAD[i] != look {
            // YYFALLBACK
            let fallback = YY_FALLBACK[look as usize];
            if fallback != 0 {
                debug_assert!(YY_FALLBACK[fallback as usize] == 0); // o laço de fallback termina
                look = fallback;
                continue;
            }
            // YYWILDCARD
            let j = i - look as usize + YYWILDCARD;
            if YY_LOOKAHEAD[j] as usize == YYWILDCARD && look > 0 {
                return YY_ACTION[j];
            }
            return YY_DEFAULT[stateno as usize];
        }
        return YY_ACTION[i];
    }
}

/// `yy_find_reduce_action`: a ação para o não-terminal `look` no estado `stateno` (sem
/// `YYERRORSYMBOL`, valem os asserts do C: o estado e o deslocamento sempre estão na tabela).
pub fn yy_find_reduce_action(stateno: u16, look: u16) -> u16 {
    debug_assert!(stateno as usize <= YY_REDUCE_COUNT);
    debug_assert!(look != YYNOCODE);
    let i = YY_REDUCE_OFST[stateno as usize] as i32 + look as i32;
    debug_assert!(i >= 0 && (i as usize) < YY_ACTTAB_COUNT);
    debug_assert!(YY_LOOKAHEAD[i as usize] == look);
    YY_ACTION[i as usize]
}

/// `yy_shift`: empilha o token `minor` com o símbolo `major`, no estado `new_state`.
pub fn yy_shift(p: &mut YyParser, mut new_state: u16, major: u16, minor: Token) {
    p.tos += 1;
    if p.tos >= p.stack.len() {
        p.grow_stack();
    }
    if new_state > YY_MAX_SHIFT {
        new_state += YY_MIN_REDUCE - YY_MIN_SHIFTREDUCE;
    }
    let e = &mut p.stack[p.tos];
    e.stateno = new_state;
    e.major = major;
    e.minor = YyMinor::Yy0(minor);
}

/// O trecho final de `yy_reduce` do C (depois do `switch` das ações): acha o estado de destino
/// pelo goto do não-terminal da regra, recolhe a pilha e empilha o lado esquerdo. Deve ser
/// chamado por `crate::parse_reduce::yy_reduce` quando a ação da regra `yyruleno` termina; o valor
/// devolvido é a ação que `parser` entrega ao laço (o `yyact` do C).
///
/// As entradas desempilhadas (acima da nova posição do topo) têm o valor solto aqui, o que no C
/// eram os `yy_destructor` emitidos pelo lemon para os símbolos do lado direito não usados.
pub fn yy_reduce_goto(p: &mut YyParser, yyruleno: u32) -> u16 {
    debug_assert!((yyruleno as usize) < YY_RULE_INFO_LHS.len());
    let yygoto = YY_RULE_INFO_LHS[yyruleno as usize];
    let yysize = YY_RULE_INFO_NRHS[yyruleno as usize] as isize;
    let old_tos = p.tos;
    let base = (old_tos as isize + yysize) as usize;
    let yyact = yy_find_reduce_action(p.stack[base].stateno, yygoto);

    // Não há SHIFTREDUCE em não-terminais (o gerador os simplificou em REDUCE puros), e um
    // REDUCE nunca é seguido de erro.
    debug_assert!(!(yyact > YY_MAX_SHIFT && yyact <= YY_MAX_SHIFTREDUCE));
    debug_assert!(yyact != YY_ERROR_ACTION);

    let new_tos = base + 1;
    for k in (new_tos + 1)..=old_tos {
        drop(std::mem::take(&mut p.stack[k].minor));
    }
    p.tos = new_tos;
    let e = &mut p.stack[new_tos];
    e.stateno = yyact;
    e.major = yygoto;
    yyact
}

/// `yy_syntax_error`: a ação `%syntax_error` do parse.y (`near "%T": syntax error`, ou
/// `incomplete input` quando o token é o fim do texto).
fn yy_syntax_error(p_parse: &mut Parse, db: &mut Connection, token: &Token) {
    if token.z.first().copied().unwrap_or(0) != 0 {
        let arg = crate::build::token_arg(p_parse, token);
        crate::util::error_msg(db, p_parse, b"near \"%T\": syntax error", &[arg]);
    } else {
        crate::util::error_msg(db, p_parse, b"incomplete input", &[]);
    }
}

/// `yy_accept`: a ação `%parse_accept` (vazia no parse.y); sobra a invariante do C.
fn yy_accept(p: &YyParser) {
    debug_assert!(p.tos == 0);
}

/// `sqlite3Parser`: alimenta o autômato com um token (`yymajor` é o código `TK_*`, `yyminor` o
/// texto). `p_parse` é o `%extra_context` e `db` a conexão dona do parse.
///
/// Sem recuperação de erro (`YYNOERRORRECOVERY`): num erro de sintaxe chama `yy_syntax_error`,
/// descarta o token e devolve o controle; o chamador (`sqlite3RunParser`) decide parar por
/// `pParse->nErr`.
pub fn parser(p: &mut YyParser, yymajor: i32, yyminor: Token, p_parse: &mut Parse, db: &mut Connection) {
    debug_assert!(p.tos < p.stack.len());
    let mut yyact = p.stack[p.tos].stateno;
    loop {
        debug_assert!(yyact == p.stack[p.tos].stateno);
        yyact = yy_find_shift_action(yymajor as u16, yyact);
        if yyact >= YY_MIN_REDUCE {
            let yyruleno = (yyact - YY_MIN_REDUCE) as u32;
            // Garante espaço para empilhar o lado esquerdo de uma regra de lado direito vazio.
            if YY_RULE_INFO_NRHS[yyruleno as usize] == 0 && p.tos >= p.stack.len() - 1 {
                p.grow_stack();
            }
            yyact = crate::parse_reduce::yy_reduce(p, yyruleno, yymajor, &yyminor, p_parse, db);
        } else if yyact <= YY_MAX_SHIFTREDUCE {
            yy_shift(p, yyact, yymajor as u16, yyminor);
            return;
        } else if yyact == YY_ACCEPT_ACTION {
            p.tos -= 1;
            yy_accept(p);
            return;
        } else {
            debug_assert!(yyact == YY_ERROR_ACTION);
            yy_syntax_error(p_parse, db, &yyminor);
            // O `yy_destructor` do token descartado é o `drop` de `yyminor` ao sair.
            return;
        }
    }
}

/// `sqlite3ParserFallback`: o token de fallback do token canônico `i_token`, ou 0 se não tem.
pub fn parser_fallback(i_token: i32) -> i32 {
    debug_assert!((i_token as usize) < YY_FALLBACK.len());
    YY_FALLBACK[i_token as usize] as i32
}
