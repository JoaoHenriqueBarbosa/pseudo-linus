//! `parse.c` (gerado pelo lemon a partir de `parse.y`): tabelas LALR e o motor do autômato de
//! pilha. A função `yy_reduce` (as ações semânticas, `parse_c.006` em diante) fica em
//! `crate::parse_reduce`; aqui está tudo o que ela usa para fechar a redução
//! (`yy_reduce_goto`) e a pilha (`YyParser`).
//!
//! Configuração do Debian 13 resolvida como `#ifdef`: `YYNOERRORRECOVERY` ligado (sem `yyerrcnt`,
//! sem `yy_parse_failed`, sem símbolo `error`), `YYFALLBACK` e `YYWILDCARD` ligados,
//! `YYGROWABLESTACK` ligado, `NDEBUG` ligado (sem `yyTraceFILE`, sem `yyRuleName`, sem
//! `yyTraceShift`), `YYCOVERAGE` desligado.
//!
//! As tabelas são as do `parse.c` gerado pelo lemon 3.46.1 com `SQLITE_ENABLE_UPDATE_DELETE_LIMIT`
//! (`upstream/parse-ul/parse.c`), que é como o sqlite3 do Debian é compilado: `DELETE` e `UPDATE`
//! aceitam `ORDER BY ... LIMIT` (regras 152 e 159). O número de regras não muda em relação ao
//! amalgamation (409), mas as tabelas LALR sim (587 estados).
//!
//! Modelo de dados (CONVENTIONS.md): o `yyStackEntry.minor` do C é uma união; aqui é o enum
//! `YyMinor`, com um valor possuído por variante. Os `%destructor` do lemon somem: soltar um
//! `YyMinor` (por `mem::take` ou ao sobrescrever) libera a árvore, que é a posse em árvore do
//! modelo v2. Por isso uma ação de redução que MOVE um valor da pilha deve fazê-lo com
//! `std::mem::take(&mut yyp.msp(k).minor)`, deixando `YyMinor::Init` no lugar (como o C, que
//! deixava o ponteiro velho e simplesmente não o destruía).
//!
//! `yymsp[k]` do C (`k` negativo ou zero, relativo ao topo) é `yyp.msp(k)`. O C também escreve em
//! `yymsp[1]` nas regras de lado direito vazio, antes do empilhamento: a pilha é um `Vec` que
//! mantém sempre pelo menos uma entrada acima do topo (ver `parser`), e `tos` é o índice do topo.

